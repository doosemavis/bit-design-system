// Builds bit's icons from packages/core/src/icons/icons.json and the pinned @material-symbols/svg-700
// (a devDependency of @bit-ds/react). Writes two committed files:
//   packages/react/src/icons/icons.generated.ts   one IconData const per icon (regular and fill paths), plus ICON_GROUPS
//   packages/core/src/icons/icons.generated.css   one rule per icon with --_bit-icon and --_bit-icon-fill (shipped as icons.css)
// Run `npm run icons` after editing icons.json. scripts/build-icons.test.mjs fails when they drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { iconClassName, iconExportName, iconName } from './icon-names.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const requireFromReact = createRequire(resolve(root, 'packages/react/package.json'));
const PACKAGE = '@material-symbols/svg-700';

export const OUTPUTS = {
  list: resolve(root, 'packages/core/src/icons/icons.json'),
  ts: resolve(root, 'packages/react/src/icons/icons.generated.ts'),
  css: resolve(root, 'packages/core/src/icons/icons.generated.css'),
};

const SOURCE = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="48" height="48" viewBox="0 -960 960 960"><path d="([^"]+)"\/><\/svg>\n?$/;
const EXPORT = /^icon[A-Z][A-Za-z0-9]*$/;

/** The one path in a Material file; throws when the file is anything else. */
function pathOf(file, svg) {
  const match = SOURCE.exec(svg);
  if (!match) throw new Error(`build-icons: ${file} is not a single 960-grid path`);
  return match[1];
}

/** The SVG as a CSS url(): only the characters a data URI needs are escaped, so the file stays small. */
function dataUri(path) {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 -960 960 960'><path d='${path}'/></svg>`;
  return `url("data:image/svg+xml,${svg.replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;
}

/**
 * The two files' text. `groups` is icons.json; `readSvg(file)` returns a file from the package's sharp/ folder.
 * Pure: the same input always gives the same output.
 */
export function buildIcons({ groups, readSvg, version }) {
  const seen = new Set();
  const exports = new Map(); // exportName -> material name
  const icons = []; // { material, exportName, name, path, fillPath }, in list order
  const groupLines = [];
  for (const [label, names] of Object.entries(groups)) {
    const exportNames = [];
    for (const material of names) {
      if (seen.has(material)) throw new Error(`build-icons: listed twice: ${material}`);
      seen.add(material);
      const exportName = iconExportName(material);
      if (!EXPORT.test(exportName)) throw new Error(`build-icons: ${material} does not make a valid export name`);
      if (exports.has(exportName)) throw new Error(`build-icons: ${material} maps to the same export as ${exports.get(exportName)}`);
      exports.set(exportName, material);
      icons.push({
        material,
        exportName,
        name: iconName(material),
        path: pathOf(`${material}.svg`, readSvg(`${material}.svg`)),
        fillPath: pathOf(`${material}-fill.svg`, readSvg(`${material}-fill.svg`)),
      });
      exportNames.push(exportName);
    }
    groupLines.push(`  { label: '${label.replace(/'/g, "\\'")}', icons: [${exportNames.join(', ')}] },`);
  }
  const ts = [
    `// Generated by scripts/build-icons.mjs from packages/core/src/icons/icons.json and ${PACKAGE} ${version}. Do not edit.`,
    '// Artwork: Material Symbols Sharp 700, Copyright Google LLC, Apache License 2.0.',
    "import type { IconData, IconGroup } from './types';",
    '',
    ...icons.map((i) => `export const ${i.exportName}: IconData = { name: '${i.name}', path: '${i.path}', fillPath: '${i.fillPath}' };`),
    '',
    "/** The curated set in the gallery's order. */",
    'export const ICON_GROUPS: readonly IconGroup[] = [',
    ...groupLines,
    '];',
    '',
  ].join('\n');
  const css = [
    '/* Generated by scripts/build-icons.mjs. Do not edit. Shipped as @bit-ds/react/icons.css, never inside styles.css. */',
    `/* Artwork: Material Symbols Sharp 700 (${PACKAGE} ${version}), Apache License 2.0, Copyright Google LLC. */`,
    "/* In bit's components layer, as styles.css is, so your app's own unlayered styles win. */",
    '@layer bit.reset, bit.tokens, bit.components;',
    '@layer bit.components {',
    ...icons.map((i) => `.${iconClassName(i.material)}{--_bit-icon:${dataUri(i.path)};--_bit-icon-fill:${dataUri(i.fillPath)}}`),
    '}',
    '',
  ].join('\n');
  return { ts, css };
}

/** icons.json, a reader over the pinned package's sharp/ folder, and that package's version. */
export function loadInputs() {
  const groups = JSON.parse(readFileSync(OUTPUTS.list, 'utf8'));
  const pkgJson = requireFromReact.resolve(`${PACKAGE}/package.json`);
  const sharp = resolve(dirname(pkgJson), 'sharp');
  const { version } = JSON.parse(readFileSync(pkgJson, 'utf8'));
  return { groups, readSvg: (file) => readFileSync(resolve(sharp, file), 'utf8'), version };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { ts, css } = buildIcons(loadInputs());
  writeFileSync(OUTPUTS.ts, ts);
  writeFileSync(OUTPUTS.css, css);
  console.log(`build-icons: wrote ${(ts.match(/^export const icon/gm) ?? []).length} icons`);
}
